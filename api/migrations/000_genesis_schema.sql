-- Enum types ---------------------------------------------------------
--
-- CREATE TYPE has no IF NOT EXISTS, so each one checks pg_type first.
-- Note that orders.direction and shipping.direction are different types
-- that happen to share a name; the schema is what keeps them apart.

DO $$ BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_type t JOIN pg_namespace n ON n.oid = t.typnamespace
    WHERE t.typname = 'direction' AND n.nspname = 'orders'
  ) THEN
    CREATE TYPE orders.direction AS ENUM ('purchase', 'sale');
  END IF;
END $$;

DO $$ BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_type t JOIN pg_namespace n ON n.oid = t.typnamespace
    WHERE t.typname = 'direction' AND n.nspname = 'shipping'
  ) THEN
    CREATE TYPE shipping.direction AS ENUM ('Inbound', 'Outbound', 'Return');
  END IF;
END $$;

DO $$ BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_type t JOIN pg_namespace n ON n.oid = t.typnamespace
    WHERE t.typname = 'sales_tax_metal_category' AND n.nspname = 'tax'
  ) THEN
    CREATE TYPE tax.sales_tax_metal_category AS ENUM ('Gold', 'Silver', 'Platinum', 'Palladium', 'All');
  END IF;
END $$;

DO $$ BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_type t JOIN pg_namespace n ON n.oid = t.typnamespace
    WHERE t.typname = 'sales_tax_product_type' AND n.nspname = 'tax'
  ) THEN
    CREATE TYPE tax.sales_tax_product_type AS ENUM ('Coin', 'Bar', 'Collectible', 'All');
  END IF;
END $$;

