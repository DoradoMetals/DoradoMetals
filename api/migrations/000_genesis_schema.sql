-- Enum types ---------------------------------------------------------
--
-- CREATE TYPE has no IF NOT EXISTS, so each one checks pg_type first.
-- Note that orders.direction and shipping.direction are different types
-- that happen to share a name; the schema is what keeps them apart.

DO $$ BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_type t JOIN pg_namespace n ON n.oid = t.typnamespace
    WHERE t.typname = 'category' AND n.nspname = 'fulfillments'
  ) THEN
    CREATE TYPE fulfillments.category AS ENUM ('SHIPMENT', 'PICKUP', 'DIRECT');
  END IF;
END $$;

DO $$ BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_type t JOIN pg_namespace n ON n.oid = t.typnamespace
    WHERE t.typname = 'email_kind' AND n.nspname = 'media'
  ) THEN
    CREATE TYPE media.email_kind AS ENUM ('purchase_order_created', 'purchase_order_priced', 'sales_order_to_supplier', 'auth_verification');
  END IF;
END $$;

DO $$ BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_type t JOIN pg_namespace n ON n.oid = t.typnamespace
    WHERE t.typname = 'email_status' AND n.nspname = 'media'
  ) THEN
    CREATE TYPE media.email_status AS ENUM ('sent', 'failed');
  END IF;
END $$;

DO $$ BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_type t JOIN pg_namespace n ON n.oid = t.typnamespace
    WHERE t.typname = 'pdf_kind' AND n.nspname = 'media'
  ) THEN
    CREATE TYPE media.pdf_kind AS ENUM ('packing_list', 'return_packing_list', 'invoice', 'sales_order_invoice');
  END IF;
END $$;

