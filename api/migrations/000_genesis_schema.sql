-- baseline: 002-049
--
-- The schema itself. Creates every domain-namespaced schema from nothing.
--
-- This migration exists because the others assume it. The domain schemas were
-- built directly in dev in January and their DDL was never committed, so every
-- migration from 002 onwards - all of which ALTER those tables - could only run
-- on this one machine. Migration 002 opens with `ALTER TABLE core.leads`, which
-- on any other database is an immediate abort.
--
-- Numbered 000 so it sorts ahead of 001 and runs first on a database that has
-- nothing. The runner applies pending files in filename order regardless of
-- what has already been applied, so adding it after the fact is fine: on dev
-- every statement is guarded and the whole file is a no-op.
--
-- GENERATED by scripts/dump-schema.mjs from the dev catalog. Regenerate rather
-- than editing by hand, and only while dev is still the definition of correct.
--
-- The `baseline: 002-049` line above matters. This file is generated from dev,
-- which has migrations 002-049 already applied, so the shape it creates is
-- the shape *after* those ran. 001 is deliberately not covered: it indexes
-- foreign keys on exchange, which any real database still wants. On a fresh database they must
-- therefore be recorded as done rather than replayed - the first ALTER TABLE
-- ADD CONSTRAINT among them would fail, because Postgres has no IF NOT EXISTS
-- for that. The runner reads the marker and stamps them. On dev they are
-- already in the ledger, so nothing is stamped and nothing is skipped.
--
-- This file creates structure and nothing else. Populating the tables from
-- exchange is a separate migration, because it is a different kind of risk.
--
-- exchange is untouched.

