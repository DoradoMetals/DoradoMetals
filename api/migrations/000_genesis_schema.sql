--
-- Before the tables, not after: a STORED generated column names a
-- function in its expression, and CREATE TABLE resolves it there and
-- then. inventory.lots.content calls metals.fine_content.

CREATE OR REPLACE FUNCTION inventory.assay_stamp()
 RETURNS trigger
 LANGUAGE plpgsql
AS $function$
BEGIN
  IF (NEW.pre_melt, NEW.post_melt, NEW.purity, NEW.unit, NEW.quantity)
     IS DISTINCT FROM
     (OLD.pre_melt, OLD.post_melt, OLD.purity, OLD.unit, OLD.quantity)
  THEN
    NEW.assayed_at := now();
  END IF;
  RETURN NEW;
END $function$;

CREATE OR REPLACE FUNCTION inventory.declare_stamp()
 RETURNS trigger
 LANGUAGE plpgsql
AS $function$
BEGIN
  NEW.declared_unit := COALESCE(NEW.declared_unit, NEW.unit);
  NEW.declared_quantity := COALESCE(NEW.declared_quantity, NEW.quantity);
  NEW.declared_pre_melt := COALESCE(NEW.declared_pre_melt, NEW.pre_melt);
  NEW.declared_post_melt := COALESCE(NEW.declared_post_melt, NEW.post_melt);
  NEW.declared_purity := COALESCE(NEW.declared_purity, NEW.purity);
  RETURN NEW;
END $function$;

CREATE OR REPLACE FUNCTION metals.fine_content(weight numeric, unit text, purity numeric)
 RETURNS numeric
 LANGUAGE plpgsql
 IMMUTABLE
AS $function$
DECLARE
  troy_oz numeric;
BEGIN
  IF weight IS NULL OR purity IS NULL THEN
    RETURN NULL;
  END IF;

  troy_oz := CASE lower(coalesce(unit, ''))
    WHEN 't oz' THEN weight
    WHEN 'g'    THEN weight / 31.1034768
    WHEN 'dwt'  THEN weight / 20
    WHEN 'lb'   THEN weight * (175.0 / 12.0)
  END;

  IF troy_oz IS NULL THEN
    RAISE EXCEPTION USING
      ERRCODE = 'invalid_parameter_value',
      MESSAGE = format('%L is not a weight this business quotes in', unit);
  END IF;

  RETURN purity * troy_oz;
END;
$function$;

CREATE OR REPLACE FUNCTION rates.log_change()
 RETURNS trigger
 LANGUAGE plpgsql
AS $function$
DECLARE
  cols   text[] := ARRAY['metal_id', 'unit', 'min_qty', 'max_qty', 'scrap_pct', 'bullion_pct'];
  before jsonb := to_jsonb(OLD);
  after  jsonb := to_jsonb(NEW);
  col    text;
BEGIN
  FOREACH col IN ARRAY cols LOOP
    IF before -> col IS DISTINCT FROM after -> col THEN
      INSERT INTO rates.rate_history (rate_id, field, old_value, new_value, actor_id, actor_name)
      VALUES (NEW.id, col, before ->> col, after ->> col, NEW.updated_by_id, NEW.updated_by);
    END IF;
  END LOOP;
  RETURN NEW;
END;
$function$;

