  )
  VALUES (
    NEW.id, NEW.email, NEW.name, NEW."createdAt", NEW."updatedAt", NEW."emailVerified",
    NEW.image, NEW.role, NEW."stripeCustomerId", COALESCE(NEW.dorado_funds, 0),
    NEW.banned, NEW."banReason", NEW."banExpires"
  )
  ON CONFLICT (id) DO UPDATE SET
    email = EXCLUDED.email, name = EXCLUDED.name,
    "updatedAt" = EXCLUDED."updatedAt", "emailVerified" = EXCLUDED."emailVerified",
    image = EXCLUDED.image, role = EXCLUDED.role,
    "stripeCustomerId" = EXCLUDED."stripeCustomerId", banned = EXCLUDED.banned,
    "banReason" = EXCLUDED."banReason", "banExpires" = EXCLUDED."banExpires";
    -- dorado_funds DELIBERATELY absent: exchange owns it. The INSERT above
    -- seeds a NEW user's balance at 0; an existing row's balance is never
    -- touched from this side - that is the $1000 bug, direction-proofed.
  RETURN NEW;
END;
$function$;

CREATE OR REPLACE FUNCTION auth.mirror_session_to_exchange()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
BEGIN
  IF pg_trigger_depth() > 1 THEN RETURN NEW; END IF;
  INSERT INTO exchange.session (
    id, "userId", token, "expiresAt", "ipAddress", "userAgent",
    "createdAt", "updatedAt", "impersonatedBy"
  )
  VALUES (
    NEW.id, NEW."userId", NEW.token, NEW."expiresAt", NEW."ipAddress",
    NEW."userAgent", NEW."createdAt", NEW."updatedAt", NEW."impersonatedBy"
  )
  ON CONFLICT (id) DO UPDATE SET
    token = EXCLUDED.token, "expiresAt" = EXCLUDED."expiresAt",
    "updatedAt" = EXCLUDED."updatedAt", "impersonatedBy" = EXCLUDED."impersonatedBy";
  RETURN NEW;
END;
$function$;

-- Views --------------------------------------------------------------
--
-- The compat views, which reassemble an exchange-shaped row from the
-- tables it was split across. Only the parity check reads them.

CREATE OR REPLACE VIEW metals.exchange_compat AS
 SELECT m.id,
    m.name AS type,
    s.ask AS ask_spot,
    s.bid AS bid_spot,
    s.percent_change,
    s.dollar_change
   FROM metals.metals m
     LEFT JOIN spots.spots s ON s.metal_id = m.id;

CREATE OR REPLACE VIEW products.mints_exchange_compat AS
 SELECT mint.id,
    mint.name,
    mint.type,
    mint.country,
    org.description,
    org.website,
    (mint.created_at AT TIME ZONE 'UTC'::text) AS created_at,
    (mint.updated_at AT TIME ZONE 'UTC'::text) AS updated_at
   FROM products.mints mint
     JOIN organizations.organizations org ON org.id = mint.organization_id;

CREATE OR REPLACE VIEW refiners.exchange_compat AS
 SELECT r.id,
    o.name,
    o.email,
    o.phone,
    o.created_at,
    o.updated_at,
    r.logo,
    o.enabled AS is_active
   FROM refiners.refiners r
     JOIN organizations.organizations o ON o.id = r.organization_id;

CREATE OR REPLACE VIEW shipping.carriers_exchange_compat AS
 SELECT c.id,
    o.name,
    o.email,
    o.phone,
    c.logo,
    o.enabled AS is_active,
    o.created_at,
    o.updated_at
   FROM shipping.carriers c
     JOIN organizations.organizations o ON o.id = c.organization_id;
