-- baseline: 002-134
--
-- The schema itself. Creates every domain-namespaced schema from nothing.
--
-- This migration exists because the others assume it. The domain schemas were
-- built directly in dev in January and their DDL was never committed, so every
-- migration from 002 onwards - all of which ALTER those tables - could only run
-- on this one machine. Migration 002 opens with `ALTER TABLE core.leads`, which
-- on any other database is an immediate abort.
--
-- Numbered 000 so it sorts ahead of 001 and runs first on a database that has
-- nothing. The runner applies pending files in filename order regardless of
-- what has already been applied, so adding it after the fact is fine: on dev
-- every statement is guarded and the whole file is a no-op.
--
-- GENERATED by scripts/dump-schema.mjs from the dev catalog. Regenerate rather
-- than editing by hand, and only while dev is still the definition of correct.
--
-- The `baseline: 002-134` line above matters, and it says more than it used to.
-- This file is generated from DEV, which has every migration applied, so the
-- shape it creates is the shape after ALL of them - not the shape after 049.
-- It read `002-049` until 2026-09-06, and that understatement is the single
-- bug the UAT rehearsal met six times (F3-F6): migrations 050 onwards were
-- replayed against a database that already had their result, and each one that
-- named a column a later migration drops, or created an object this file
-- already created, aborted the chain.
--
-- So the range now runs to the last migration this file was generated behind.
-- 001 is deliberately still outside it: it indexes foreign keys on exchange,
-- which any real database still wants.
--
-- WHAT A BASELINE STAMPS IS SHAPE, NEVER ROWS. The runner splits the covered
-- set: a migration whose every statement is DDL is recorded as done, and one
-- that carries an INSERT, UPDATE or DELETE still RUNS, in its own place in the
-- order. Stamping a backfill is how the rehearsal ended with an empty product
-- catalogue, no metals and no spot prices (F7); `scripts/lib/baseline.ts`
-- `isDdlOnly` is where the split is decided and it treats anything it cannot
-- read as data, which is the safe direction.
--
-- The stamping is only sound on a database genesis builds from NOTHING, since
-- every statement here is IF NOT EXISTS and cannot repair a table that already
-- exists. The runner therefore refuses to apply this file's baseline while any
-- non-protected schema still holds a table, and points at
-- `migrate:reset-january` - ruling 82, Jacob 2026-09-06: drop the abandoned
-- January schemas after the dump and let genesis and the backfills rebuild
-- them. exchange is never dropped.
--
-- This file creates structure and nothing else. Populating the tables from
-- exchange is a separate migration, because it is a different kind of risk.
--
-- exchange is untouched.

