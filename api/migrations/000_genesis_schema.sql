-- Constraints --------------------------------------------------------
--
-- Primary keys, uniques and checks first, then foreign keys, so a key can
-- always find the unique index it points at. ALTER TABLE ADD CONSTRAINT
-- has no IF NOT EXISTS either, hence the catalog check on each.

DO $$ BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint con
    JOIN pg_class c ON c.oid = con.conrelid
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE con.conname = 'account_accountId_key' AND c.relname = 'account' AND n.nspname = 'auth'
  ) THEN
    ALTER TABLE auth.account ADD CONSTRAINT "account_accountId_key" UNIQUE ("accountId");
  END IF;
END $$;
DO $$ BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint con
    JOIN pg_class c ON c.oid = con.conrelid
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE con.conname = 'account_pkey' AND c.relname = 'account' AND n.nspname = 'auth'
  ) THEN
    ALTER TABLE auth.account ADD CONSTRAINT account_pkey PRIMARY KEY (id);
  END IF;
END $$;
DO $$ BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint con
    JOIN pg_class c ON c.oid = con.conrelid
    JOIN pg_namespace n ON n.oid = c.relnamespace
