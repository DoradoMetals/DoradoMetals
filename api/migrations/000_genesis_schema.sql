    ALTER TABLE shipping.shipments ADD CONSTRAINT shipments_shipper_address_fk FOREIGN KEY (shipper_address_id) REFERENCES places.addresses(id);
  END IF;
END $$;
DO $$ BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint con
    JOIN pg_class c ON c.oid = con.conrelid
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE con.conname = 'shipment_events_shipment_fk' AND c.relname = 'tracking' AND n.nspname = 'shipping'
  ) THEN
    ALTER TABLE shipping.tracking ADD CONSTRAINT shipment_events_shipment_fk FOREIGN KEY (shipment_id) REFERENCES shipping.shipments(id) ON DELETE CASCADE;
  END IF;
END $$;
DO $$ BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint con
    JOIN pg_class c ON c.oid = con.conrelid
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE con.conname = 'current_spots_metal_id_fkey' AND c.relname = 'spots' AND n.nspname = 'spots'
  ) THEN
    ALTER TABLE spots.spots ADD CONSTRAINT current_spots_metal_id_fkey FOREIGN KEY (metal_id) REFERENCES metals.metals(id);
