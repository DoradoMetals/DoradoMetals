import fs from "node:fs";
import path from "node:path";

const SRC = process.argv[2]
  ?? path.join(import.meta.dirname, "..", "..", "unified_payments.csv");
const OUT = path.join(import.meta.dirname, "..", "migrations", "055_seed_stripe_reconciliation.sql");

const KEEP = {
  charge_id: "id",
  created_at: "Created date (UTC)",
  amount: "Amount",
  amount_refunded: "Amount Refunded",
  fee: "Fee",
  currency: "Currency",
  captured: "Captured",
  payment_intent_id: "PaymentIntent ID",
  refunded_at: "Refunded date (UTC)",
  status: "Status",
  payment_source_type: "Payment Source Type",
  stripe_customer_id: "Customer ID",
  livemode: "Mode",
};

function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = "";
  let quoted = false;
  let i = 0;

  while (i < text.length) {
    const ch = text[i];

    if (quoted) {
      if (ch === '"') {
        if (text[i + 1] === '"') { field += '"'; i += 2; continue; }
        quoted = false; i++; continue;
      }
      field += ch; i++; continue;
    }

    if (ch === '"') { quoted = true; i++; continue; }
    if (ch === ",") { row.push(field); field = ""; i++; continue; }
    if (ch === "\r") { i++; continue; }
    if (ch === "\n") { row.push(field); rows.push(row); row = []; field = ""; i++; continue; }
    field += ch; i++;
  }
  if (field.length || row.length) { row.push(field); rows.push(row); }
  return rows.filter((r) => r.some((c) => c !== ""));
}

const lit = (v) => (v == null || v === "" ? "NULL" : `'${String(v).replace(/'/g, "''")}'`);
const num = (v) => (v == null || v === "" ? "NULL" : `${Number(v)}`);
const bool = (v) => (v === "" || v == null ? "NULL" : v === "true" ? "true" : v === "false" ? "false" : "NULL");

if (!fs.existsSync(SRC)) {
  console.error(`no Stripe export at ${SRC}`);
  console.error(`pass a path, or drop unified_payments.csv at the repo root`);
  process.exit(1);
}

const rows = parseCsv(fs.readFileSync(SRC, "utf8"));
const header = rows[0];
const idx = {};
for (const [col, name] of Object.entries(KEEP)) {
  const at = header.indexOf(name);
  if (at === -1) {
    console.error(`the export has no "${name}" column - is this a payments export?`);
    process.exit(1);
  }
  idx[col] = at;
}

const seen = new Set();
const values = [];
let skipped = 0;

for (const r of rows.slice(1)) {
  const pi = r[idx.payment_intent_id];
  if (!pi) { skipped++; continue; }
  if (seen.has(pi)) { skipped++; continue; }
  seen.add(pi);

  values.push(
    `  (${lit(pi)}, ${lit(r[idx.charge_id])}, ${lit(r[idx.created_at])}::timestamp AT TIME ZONE 'UTC', ` +
    `${num(r[idx.amount])}, ${num(r[idx.amount_refunded])}, ${num(r[idx.fee])}, ` +
    `${lit(r[idx.currency])}, ${bool(r[idx.captured])}, ${lit(r[idx.status])}, ` +
    `${r[idx.refunded_at] ? `${lit(r[idx.refunded_at])}::timestamp AT TIME ZONE 'UTC'` : "NULL"}, ` +
    `${lit(r[idx.payment_source_type])}, ${lit(r[idx.stripe_customer_id])}, ` +
    `${r[idx.livemode] === "Live" ? "true" : r[idx.livemode] === "Test" ? "false" : "NULL"})`
  );
}

const settled = rows.slice(1).filter((r) => r[idx.charge_id]).length;

const sql = `-- Stripe reconciliation data, from a dashboard export.
--
-- GENERATED by scripts/dump-stripe-reconciliation.mjs. Regenerate rather than
-- editing by hand, from a fresh export at the repo root:
--
--   node scripts/dump-stripe-reconciliation.mjs
--
-- ${values.length} payment intents, ${settled} of which settled into a charge.
-- Export taken ${new Date().toISOString().slice(0, 10)}.
--
-- Amounts are in DOLLARS, as Stripe exports them. exchange.payment_intents
-- stores CENTS.
--
-- Carries no personal data: no cardholder name, no billing address, no card
-- last4. See 054 for why this table exists and why it is not a correction
-- applied to exchange.
--
-- Idempotent: keyed on payment_intent_id, and re-running updates in place.
-- exchange is not read or written here at all.

INSERT INTO payments.stripe_charges (
  payment_intent_id, charge_id, created_at,
  amount, amount_refunded, fee,
  currency, captured, status,
  refunded_at, payment_source_type, stripe_customer_id, livemode
)
VALUES
${values.join(",\n")}
ON CONFLICT (payment_intent_id) DO UPDATE SET
  charge_id           = EXCLUDED.charge_id,
  created_at          = EXCLUDED.created_at,
  amount              = EXCLUDED.amount,
  amount_refunded     = EXCLUDED.amount_refunded,
  fee                 = EXCLUDED.fee,
  currency            = EXCLUDED.currency,
  captured            = EXCLUDED.captured,
  status              = EXCLUDED.status,
  refunded_at         = EXCLUDED.refunded_at,
  payment_source_type = EXCLUDED.payment_source_type,
  stripe_customer_id  = EXCLUDED.stripe_customer_id,
  livemode            = EXCLUDED.livemode;
`;

fs.writeFileSync(OUT, sql);
console.log(`wrote ${path.relative(process.cwd(), OUT)}`);
console.log(`  ${values.length} intents, ${settled} settled, ${skipped} row(s) skipped`);
